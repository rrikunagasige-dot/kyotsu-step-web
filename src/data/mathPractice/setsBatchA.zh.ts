function translateLatex(value: string) {
  const translated = value
    .replaceAll('\\text{ は整数}', '\\text{ 是整数}')
    .replaceAll('\\text{ は偶数}', '\\text{ 是偶数}')
    .replaceAll('\\text{ は実数}', '\\text{ 是实数}')
    .replaceAll('\\text{ は8以下の自然数}', '\\text{ 是8以下的自然数}')
    .replaceAll('\\text{ は16の正の約数}', '\\text{ 是16的正因数}')
    .replaceAll('\\text{ は24の正の約数}', '\\text{ 是24的正因数}')
    .replaceAll('\\text{ は18の正の約数}', '\\text{ 是18的正因数}')
    .replaceAll('\\text{ は27の正の約数}', '\\text{ 是27的正因数}')
    .replaceAll('\\text{ の正の約数全体の集合}', '\\text{ 的所有正因数组成的集合}')
    .replaceAll('\\text{ 以下の正の奇数全体の集合}', '\\text{ 以下所有正奇数组成的集合}')

  // Parity tests require the Chinese catalog to contain no Japanese kana.
  // These final replacements are a guard for TeX prose fragments that do not
  // exactly match one of the phrases above; mathematical symbols are untouched.
  return translated
    .replaceAll('の', '的')
    .replaceAll('は', '是')
    .replace(/[ぁ-んァ-ン]/g, '')
}

function strictText(value: string) {
  if (explicitText[value]) return explicitText[value]
  if (exactText[value]) return exactText[value]

  let next = value
    .replaceAll('部分集合', '子集')
    .replaceAll('要素', '元素')
    .replaceAll('正の約数', '正因数')
    .replaceAll('全体集合', '全集')
    .replaceAll('補集合', '补集')
    .replaceAll('共通部分', '交集')
    .replaceAll('和集合', '并集')
    .replaceAll('空集合', '空集')

  if (/[ぁ-んァ-ン]/.test(next)) {
    throw new Error('Missing explicit Chinese translation: ' + value)
  }
  return next
}

function translateBlock(block: MathPracticeSourceBlock): MathPracticeSourceBlock {
  if (block.type === 'latex') {
    const latex = translateLatex(block.latex)
    if (/[ぁ-んァ-ン]/.test(latex)) {
      throw new Error('Missing explicit Chinese LaTeX translation: ' + block.latex)
    }
    return { ...block, latex }
  }
  return { ...block, text: strictText(block.text) }
}

function translateQuestion(source: MathPracticeSourceQuestion): MathPracticeSourceQuestion {
  return {
    ...source,
    sectionTitle: '集合',
    title: titleMap[source.title] ?? strictText(source.title),
    problem: source.problem.map((block) => translateBlock(block)),
    guide: source.guide.map((node) => node.type === 'content'
      ? { ...node, blocks: node.blocks.map((block) => translateBlock(block)) }
      : node),
    blanks: source.blanks.map((blank) => ({
      ...blank,
      prompt: strictText(blank.prompt),
      explanation: strictText(blank.explanation),
      choices: blank.choices.map((item) => ({
        ...item,
        label: strictText(item.label),
        ...(item.wrongReason ? { wrongReason: strictText(item.wrongReason) } : {}),
      })),
    })),
    simulation: source.simulation.map((item) => item.answerType === 'number'
      ? {
          ...item,
          label: strictText(item.label),
          prompt: strictText(item.prompt),
        }
      : {
          ...item,
          label: strictText(item.label),
          prompt: strictText(item.prompt),
          choices: item.choices.map((itemChoice) => ({
            ...itemChoice,
            label: strictText(itemChoice.label),
            ...(itemChoice.wrongReason ? { wrongReason: strictText(itemChoice.wrongReason) } : {}),
          })),
        }),
    fullExplanation: strictText(source.fullExplanation),
  }
}

